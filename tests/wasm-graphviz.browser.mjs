/**
 * The layout engine, in a real browser, in both of them.
 *
 * Everything that matters here is a claim about a browser and nothing else:
 * that a frame with `sandbox="allow-scripts"', an opaque origin, no network
 * and `'wasm-unsafe-eval'' can instantiate a megabyte of compiled graphviz
 * and lay a graph out; that it cannot reach the page that started it; and
 * that the frame which then SHOWS the drawing is as inert as it was before
 * any of this existed.  None of that can be settled in node, and the CSP
 * keyword in particular is exactly the sort of thing one engine honours and
 * the other has never implemented -- so the file runs Firefox first and
 * Chromium second and asserts the same of each.
 *
 * The last section is the panel: a DOT figure is now two things, a drawing
 * and the source it was laid out from, and the pane offers both as tabs
 * because it has script.  The saved file says the same with `<details>'.
 */
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { join, dirname, extname, normalize } from "node:path";
import { fileURLToPath } from "node:url";
import { firefox, chromium } from "playwright";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TYPES = { ".js": "text/javascript", ".mjs": "text/javascript", ".css": "text/css",
                ".html": "text/html", ".txt": "text/plain", ".json": "application/json" };

const GRAPH = "digraph g { rankdir=LR; a -> b; b -> c; a -> c; c -> a }";

const HARNESS = `<!doctype html><meta charset="utf-8"><title>graphviz</title>
<body>
<div id="host"></div>
<script type="module">
import { layoutDot, DOT_ENGINES, releaseGraphviz } from "/lib/wasm/graphviz.js";
import { mountFigure, FIGURE_SANDBOX } from "/lib/figure/frame.js";

window.__messages = [];
window.addEventListener("message", (e) => { window.__messages.push(String(e.data)); });

window.__layout = (src, engine) => layoutDot(src, { engine });
window.__engines = DOT_ENGINES;
window.__sandbox = FIGURE_SANDBOX;
window.__mount = async (text, engine) => {
  const h = mountFigure(document.getElementById("host"), { kind: "dot", text },
                        { caption: "a graph", engine });
  window.__handle = h;
  const out = await h.ready;
  return { ok: out.ok, error: out.error || null };
};
window.__ready = true;
<\/script>
</body>`;

const server = createServer(async (req, res) => {
  const path = decodeURIComponent(new URL(req.url, "http://x").pathname);
  if (path === "/__harness") {
    res.writeHead(200, { "Content-Type": "text/html" });
    res.end(HARNESS);
    return;
  }
  const file = join(ROOT, normalize(path.slice(1)).replace(/^(\.\.[/\\])+/, ""));
  try {
    const buf = await readFile(file);
    res.writeHead(200, { "Content-Type": TYPES[extname(file)] || "application/octet-stream" });
    res.end(buf);
  } catch {
    res.writeHead(404); res.end("not found: " + path);
  }
});

await new Promise((r) => server.listen(0, "127.0.0.1", r));
const port = server.address().port;

let pass = 0, fail = 0;
const ok = (c, what) => { if (c) { pass++; console.log(`  ok   ${what}`); }
                          else { fail++; console.log(`  FAIL ${what}`); } };

for (const [name, engine] of [["firefox", firefox], ["chromium", chromium]]) {
  const browser = await engine.launch();
  const page = await browser.newPage({ viewportSize: { width: 1000, height: 800 } });
  page.on("pageerror", (e) => { fail++; console.log(`  FAIL page error: ${e.message}`); });
  await page.goto(`http://127.0.0.1:${port}/__harness`);
  await page.waitForFunction(() => window.__ready, null, { timeout: 10000 });

  console.log(`\na graph is laid out in the page — ${name}`);
  let drawing = null;
  {
    const out = await page.evaluate(([g]) => window.__layout(g, "dot"), [GRAPH]);
    ok(out.ok === true, `the engine ran and answered${out.ok ? "" : `: ${out.error}`}`);
    drawing = out.svg || "";
    ok(/Generated by graphviz version/.test(drawing),
       `and it is graphviz that answered — version ${(/version ([\d.]+)/.exec(drawing) || [])[1]}`);
    ok(out.version && out.version.length > 0,
       "which says its own version, so a drawing can be attributed to a build");
    ok(/viewBox="/.test(drawing) && !/\swidth="\d+pt"/.test(drawing),
       "what comes back is a fragment that scales, not a page-sized file");
    ok(/<title>a<\/title>/.test(drawing) && /<title>a&#45;&gt;b<\/title>/.test(drawing),
       "with the nodes and edges of the graph that was sent, and no others");
  }

  console.log(`\nthe engine frame is contained — ${name}`);
  {
    const info = await page.evaluate(() => {
      const f = [...document.querySelectorAll("iframe")]
        .find((x) => x.getAttribute("sandbox") === "allow-scripts");
      return f ? { sandbox: f.getAttribute("sandbox"), reachable: f.contentDocument !== null,
                   csp: /Content-Security-Policy[^>]*>/.test(f.srcdoc),
                   hidden: f.getBoundingClientRect().width === 0 } : null;
    });
    ok(info !== null, "the engine runs in a frame of its own, started on first use");
    ok(info.sandbox === "allow-scripts" && !/same-origin/.test(info.sandbox),
       "given script and nothing else — not same-origin");
    ok(info.reachable === false,
       "so its document is opaque to the page that started it, and the page's to it");
    ok(info.csp, "and it carries its own policy, which is what denies it the network");
    ok(info.hidden, "it draws nothing: it is a worker that happens to be a frame");
  }

  console.log(`\nthe engine is a choice, and the choice shows — ${name}`);
  {
    const neato = await page.evaluate(([g]) => window.__layout(g, "neato"), [GRAPH]);
    ok(neato.ok && neato.engine === "neato", "the same graph can be laid out by neato");
    const box = (s) => (/viewBox="([^"]+)"/.exec(s) || [])[1];
    ok(box(neato.svg) !== box(drawing),
       `and comes out a different shape — dot ${box(drawing)}, neato ${box(neato.svg)}`);
    const bogus = await page.evaluate(([g]) => window.__layout(g, "spiral"), [GRAPH]);
    ok(bogus.ok && bogus.engine === "dot",
       "an engine that does not exist falls back to dot rather than failing the figure");
  }

  console.log(`\na graph that will not parse — ${name}`);
  {
    const bad = await page.evaluate(() => window.__layout("digraph g { a -> ", "dot"));
    ok(bad.ok === false, "comes back as a failure");
    ok(typeof bad.error === "string" && bad.error.length > 0,
       `with what the engine said: "${String(bad.error).split("\n")[0].slice(0, 60)}"`);
    const after = await page.evaluate(([g]) => window.__layout(g, "dot"), [GRAPH]);
    ok(after.ok, "and the engine is still usable afterwards — one bad graph is not a dead page");
  }

  console.log(`\nthe panel shows both, and the frame still runs nothing — ${name}`);
  {
    const out = await page.evaluate(([g]) => window.__mount(g, "dot"), [GRAPH]);
    ok(out.ok, "mounting a DOT figure lays it out first");

    const fig = page.locator("#host iframe[sandbox='']");
    ok(await fig.count() === 1, "the drawing is shown in the frame that runs nothing");
    ok(await page.evaluate(() => window.__sandbox === ""),
       "whose sandbox is still empty: the engine was added beside D-M, not inside it");
    const srcdoc = await fig.getAttribute("srcdoc");
    ok(/<svg/.test(srcdoc) && /Generated by graphviz/.test(srcdoc),
       "the page it holds is the drawing");
    ok(/<details class="fig-src"/.test(srcdoc) && /digraph g/.test(srcdoc),
       "and carries the DOT source with it, in a <details> that needs no script");
    ok(/Laid out in the browser by graphviz/.test(srcdoc),
       "and says so: the geometry is the engine's work, not the model's");

    ok(await page.locator('[data-testid="figure-tab-drawing"]').count() === 1
       && await page.locator('[data-testid="figure-tab-source"]').count() === 1,
       "the pane offers the two as tabs, which it can because it has script");
    ok(await page.locator('[data-testid="figure-tab-drawing"]')
         .getAttribute("aria-selected") === "true",
       "the drawing is what you see first");
    ok(!(await page.locator('[data-testid="figure-source"]').isVisible()),
       "the source is there but behind its tab");

    await page.locator('[data-testid="figure-tab-source"]').click();
    ok(await page.locator('[data-testid="figure-source"]').isVisible()
       && (await page.locator('[data-testid="figure-source"]').textContent()).includes("rankdir=LR"),
       "clicking it shows the graph as the model wrote it");
    ok(!(await fig.isVisible()), "and puts the drawing away");

    await page.locator('[data-testid="figure-tab-drawing"]').click();
    ok(await fig.isVisible(), "and back again");

    // The engine select is the cheap half of "draw it again": same source,
    // different question, no second call to the model.
    const sel = page.locator('[data-testid="figure-engine"]');
    const before = await fig.getAttribute("srcdoc");
    await sel.selectOption("circo");
    await page.waitForFunction(
      (b) => document.querySelector("#host iframe[sandbox='']").getAttribute("srcdoc") !== b,
      before, { timeout: 15000 });
    const after = await fig.getAttribute("srcdoc");
    ok(/circo/.test(after), "choosing another engine re-lays out the same source");
    ok(after !== before, "and the drawing changes without asking the model for anything");
  }

  console.log(`\na figure the engine cannot draw — ${name}`);
  {
    const out = await page.evaluate(() => window.__mount("digraph g { a -> ", "dot"));
    ok(out.ok === false, "the mount reports the failure to its caller");
    const fig = page.locator("#host iframe[sandbox='']");
    const srcdoc = await fig.getAttribute("srcdoc");
    ok(/fig-dot/.test(srcdoc) && !/<svg/.test(srcdoc),
       "and the source is shown instead, which is what there is to show");
    ok(/did not lay out/.test(srcdoc),
       "with the reason, so a wall of text is not left unexplained");
    ok(await page.locator('[data-testid="figure-tab-drawing"]').count() === 0,
       "and no tabs: there is only one thing to look at");
  }

  await browser.close();
}

server.close();
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail ? 1 : 0);
