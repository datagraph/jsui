/**
 * The provenance footnote on a stage pane.  §2.6 R-P2, work item U-47.
 *
 * Article 50(5) asks for the disclosure "in a clear and distinguishable
 * manner at the latest at the time of the first interaction or exposure".
 * A tooltip does not meet that, and neither does a detail view the reader has
 * to open: it is met by text that is on the screen while the content is.  So
 * every stage carries one, in a small face at its foot, saying what produced
 * the stage's content and when.
 *
 * Small, not hidden.  The distinction matters and is easy to lose: the
 * footnote is quiet because it is repeated on every stage and would otherwise
 * shout, NOT because it is something to tuck away.  It never collapses with
 * its stage body, for the same reason -- a mark that the reader can fold out
 * of sight is a mark that is absent exactly when someone is looking past the
 * interface at the result.
 *
 * A stage that has produced nothing from a model says so, rather than showing
 * a mark with blanks in it: "nothing here came from a model" is a true and
 * useful disclosure, and a footnote reading "Generated by — ·" is neither.
 */

import { provenanceOf, provenanceLine, provenanceRecord } from "../../lib/provenance.js";

export const NOTE_CLASS = "prov-note";

/** Style, once per document, beside whichever pane asked first. */
export function ensureProvenanceStyle(doc, selector) {
  const id = "jsui-provenance-style";
  if (doc.getElementById(id)) return;
  const style = doc.createElement("style");
  style.id = id;
  style.textContent = `
.${NOTE_CLASS} {
  font-size: 10px; line-height: 1.5; color: #8a94a0; padding: 4px 9px 5px;
  border-top: 1px solid #f0f2f4; background: #fcfdfe;
  display: flex; gap: 6px; align-items: baseline; flex-wrap: wrap; }
.${NOTE_CLASS} .${NOTE_CLASS}-mark { font-family: ui-monospace, Menlo, Consolas, monospace; }
.${NOTE_CLASS} .${NOTE_CLASS}-none { font-style: italic; }
.${NOTE_CLASS} .${NOTE_CLASS}-act { margin-left: auto; opacity: .75; }
@media print { .${NOTE_CLASS} { color: #333; } }
`;
  (doc.head || doc.documentElement).appendChild(style);
  void selector;
}

/**
 * The footnote element.  Call `update(provenance)' as a stage learns what
 * produced it; `null' puts it back to saying nothing came from a model.
 */
export function provenanceNote(doc, provenance = null, { testid = null } = {}) {
  ensureProvenanceStyle(doc);
  const note = doc.createElement("div");
  note.className = NOTE_CLASS;
  if (testid) note.dataset.testid = testid;

  const mark = doc.createElement("span");
  const act = doc.createElement("span");
  act.className = `${NOTE_CLASS}-act`;
  act.textContent = "EU AI Act Art. 50";
  act.title = "Transparency obligation: this interface discloses what produced "
            + "its content, and when.";
  note.append(mark, act);

  const update = (p) => {
    if (!p || !(p.model || p.servedModel)) {
      mark.className = `${NOTE_CLASS}-none`;
      mark.textContent = "Nothing on this stage was produced by a model.";
      note.removeAttribute("data-provenance");
      for (const k of Object.keys({ ...note.dataset })) {
        if (k.startsWith("ai")) delete note.dataset[k];
      }
      return note;
    }
    const v = provenanceOf(p);
    mark.className = `${NOTE_CLASS}-mark`;
    mark.textContent = provenanceLine(v);
    // The machine-readable half (R-P4) travels on the element, so the mark is
    // never only prose that a reader would have to parse.
    note.setAttribute("data-provenance", "ai");
    const rec = provenanceRecord(v);
    note.dataset.aiModel = rec["ai:model"] || "";
    note.dataset.aiGeneratedAt = rec["ai:generatedAt"] || "";
    if (rec["ai:provider"]) note.dataset.aiProvider = rec["ai:provider"];
    if (rec["ai:repository"]) note.dataset.aiRepository = rec["ai:repository"];
    // Whether the identifier is the one the provider served or only the one
    // asked for: the same string, two different facts.
    note.dataset.aiModelServed = String(Boolean(rec["ai:modelServed"]));
    return note;
  };

  note._update = update;
  update(provenance);
  return note;
}

/** Put one at the foot of a stage, or refresh the one already there. */
export function markStage(section, provenance, { testid = null } = {}) {
  if (!section) return null;
  const doc = section.ownerDocument || document;
  let note = section.querySelector(`:scope > .${NOTE_CLASS}`);
  if (!note) {
    note = provenanceNote(doc, provenance, { testid });
    // After the body, and OUTSIDE it: collapsing a stage must not take its
    // disclosure with it.
    section.appendChild(note);
    return note;
  }
  note._update(provenance);
  return note;
}

export default provenanceNote;
