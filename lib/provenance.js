/**
 * The provenance mark: what produced this, when, and from what.
 *
 * `ui-generator.md' §2.6, decision D-AD, work items U-46 … U-49.  The
 * obligation it answers is EU AI Act Article 50 (Regulation (EU) 2024/1689),
 * and it is worth being exact about which part, because over-claiming a legal
 * basis is its own kind of fault:
 *
 *   50(2) binds the PROVIDER of a generative model to mark synthetic output
 *   in a machine-readable, detectable form.  That is the model vendor, not
 *   this interface.  50(4) binds the DEPLOYER -- us -- to disclose deep-fake
 *   content and AI-generated text published to inform the public.  50(5)
 *   requires whatever is disclosed to be given "in a clear and
 *   distinguishable manner at the latest at the time of the first interaction
 *   or exposure".
 *
 * So the strict obligation is narrower than what this module does, and the
 * module does more deliberately, for a reason that is not legal: WHETHER a
 * result will be published is decided after it is produced, by a user who
 * mails a page or copies an SVG.  Marking only what we predict will be
 * published marks nothing reliably, and a figure already drawn cannot be told
 * afterwards what drew it.
 *
 * Two forms, always both (R-P2, R-P4): a line a person reads, and the same
 * facts in a form a program reads without parsing prose.
 *
 * What a mark does NOT say is that the DATA is the model's.  `data-bound',
 * `data-derived' and `data-asserted' (D-P/D-S) carry that distinction, and
 * collapsing the two would label fetched rows as generated -- false, and the
 * sort of over-marking that teaches a reader to ignore every mark.  That is
 * why `repository' is part of the line: it names where the numbers came from
 * in the same breath as naming what drew them.
 */

/** The facts, normalised.  Everything optional: a partial mark beats none. */
export function provenanceOf({
  model = null, servedModel = null, served = false, provider = null,
  endpoint = null, at = null, account = null, repository = null, via = null,
} = {}) {
  const when = at ? new Date(at) : new Date();
  const identifier = servedModel || model || null;
  return {
    // The identifier to SHOW: the served one when the provider gave one.
    model: identifier,
    // Whether that is the served identifier or only the requested one, which
    // a record has to keep: they are different facts and look identical.
    served: Boolean(servedModel) || Boolean(served),
    requested: model || null,
    provider: provider || null,
    endpoint: endpoint || null,
    at: Number.isNaN(when.getTime()) ? new Date().toISOString() : when.toISOString(),
    account: account || null,
    repository: repository || null,
    via: via || null,
  };
}

/** The date as the footnote shows it: the day, which is what §2.6 asks for. */
export function provenanceDate(iso) {
  const d = iso ? new Date(iso) : new Date();
  return Number.isNaN(d.getTime()) ? "" : d.toISOString().slice(0, 10);
}

/**
 * One line, for a pane footnote or a drawn ledger.
 *
 * Deliberately short.  A mark nobody reads is a mark that has failed 50(5)'s
 * "clear and distinguishable" just as surely as no mark at all, and the way a
 * footnote stops being read is by being a paragraph.
 */
export function provenanceLine(p, { prefix = "Generated by" } = {}) {
  const v = provenanceOf(p);
  const bits = [v.model || "an unidentified model", provenanceDate(v.at)];
  const where = v.repository
    ? (v.account && !String(v.repository).includes("/") ? `${v.account}/${v.repository}`
                                                        : String(v.repository))
    : null;
  if (where) bits.push(where);
  return `${prefix} ${bits.join(" · ")}`;
}

/** The same facts as data, for a `<meta>', an attribute or an RDF record. */
export function provenanceRecord(p) {
  const v = provenanceOf(p);
  return {
    "ai:generated": true,
    "ai:model": v.model,
    "ai:modelServed": v.served,
    "ai:modelRequested": v.requested,
    "ai:provider": v.provider,
    "ai:endpoint": v.endpoint,
    "ai:generatedAt": v.at,
    "ai:repository": v.repository && v.account && !String(v.repository).includes("/")
      ? `${v.account}/${v.repository}` : v.repository,
    "ai:disclosure": "EU AI Act Article 50",
  };
}

export default provenanceLine;
